/// 生成 Then 阶段代码
fn generate_then(then: &crate::generator::schema::TestThen) -> proc_macro2::TokenStream {
    let mut assertions = Vec::new();

    // assert_success
    if then.assert_success == Some(true) {
        assertions.push(quote! {
            output.assert_success();
        });
    }

    // assert_contains
    if let Some(text) = &then.assert_contains {
        let text_str = quote::format_str!("{}", text);
        assertions.push(quote! {
            output.assert_contains(#text_str);
        });
    }

    // assert_match
    if let Some(pattern) = &then.assert_match {
        let pattern_str = quote::format_str!("{}", pattern);
        assertions.push(quote! {
            output.assert_match(#pattern_str);
        });
    }

    // assert_tool_called
    if let Some(tool) = &then.assert_tool_called {
        let tool_str = quote::format_str!("{}", tool);
        assertions.push(quote! {
            output.assert_tool_called(#tool_str);
        });
    }

    // assert_token_count
    if let Some(count) = then.assert_token_count {
        assertions.push(quote! {
            output.assert_token_count(#count);
        });
    }

    // 会话压缩相关断言
    if then.assert_compression_triggered == Some(true) {
        assertions.push(quote! {
            output.assert_compression_triggered();
        });
    }

    if let Some(threshold) = then.assert_token_count_below {
        assertions.push(quote! {
            output.assert_token_count_below(#threshold);
        });
    }

    if then.assert_system_prompt_preserved == Some(true) {
        assertions.push(quote! {
            output.assert_system_prompt_preserved();
        });
    }

    if let Some(count) = then.assert_recent_messages_count {
        assertions.push(quote! {
            output.assert_recent_messages_count(#count);
        });
    }

    quote! {
        #(#assertions)*
    }
}

/// 生成完整的测试文件内容
pub fn generate_test_file(test_suite: &crate::generator::schema::TestSuite) -> String {
    let mut code = String::new();

    // 文件头注释
    code.push_str("// Generated by tests/generator/\n");
    code.push_str("// DO NOT EDIT MANUALLY - This file is auto-generated from YAML\n");
    code.push_str(&format!("// Source: {}\n", test_suite.name));
    code.push_str(&format!("// Generated at: {}\n\n", chrono::Local::now().format("%Y-%m-%d %H:%M:%S")));

    // 引入必要的依赖
    code.push_str("use crate::common::*;\n\n");

    // 生成每个测试
    for test_case in &test_suite.tests {
        let test_code = generate_test(test_case);
        code.push_str(&test_code.to_string());
        code.push('\n');
    }

    code
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::generator::schema::TestSuite;

    #[test]
    fn test_generate_simple_test() {
        let yaml = r#"
name: "简单测试"
tests:
  - name: "测试1"
    description: "简单提示词测试"
    given:
      args: ["hello"]
    when:
      mock_response: "simple.json"
    then:
      assert_success: true
      assert_contains: "Hello"
"#;

        let suite: TestSuite = serde_yaml::from_str(yaml).unwrap();
        let test_case = &suite.tests[0];
        let code = generate_test(test_case).to_string();

        assert!(code.contains("test_测试1"));
        assert!(code.contains("async fn"));
        assert!(code.contains("TestEnv::new()"));
    }

    #[test]
    fn test_generate_test_with_env() {
        let yaml = r#"
name: "环境变量测试"
tests:
  - name: "测试环境变量"
    given:
      args: ["hello"]
      env:
        API_KEY: "test-key"
    when:
      mock_response: "simple.json"
    then:
      assert_success: true
"#;

        let suite: TestSuite = serde_yaml::from_str(yaml).unwrap();
        let test_case = &suite.tests[0];
        let code = generate_test(test_case).to_string();

        assert!(code.contains("set_env"));
        assert!(code.contains("test-key"));
    }

    #[test]
    fn test_to_snake_case() {
        assert_eq!("hello world".to_snake_case(), "hello_world");
        assert_eq!("测试名称".to_snake_case(), "ce_shi_ming_cheng"); // 简化处理
        assert_eq!("test-simple_prompt".to_test_name(), "test_test_simple_prompt");
    }
}
