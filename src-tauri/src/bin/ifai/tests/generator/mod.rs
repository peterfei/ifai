// generator/mod.rs
//
// 测试代码生成器
// 从 YAML 文件生成 Rust 测试代码

mod schema;
mod templates;

pub use schema::{TestSuite, TestCase};

use anyhow::{bail, Result};
use std::path::Path;

/// 测试代码生成器
pub struct TestGenerator {
    schema: TestSuite,
}

impl TestGenerator {
    /// 从 YAML 文件加载测试套件
    pub fn from_yaml(path: &Path) -> Result<Self> {
        let yaml_content = std::fs::read_to_string(path)?;
        let schema: TestSuite = serde_yaml::from_str(&yaml_content)?;
        Ok(Self { schema })
    }

    /// 从 YAML 字符串加载测试套件
    pub fn from_yaml_str(yaml: &str) -> Result<Self> {
        let schema: TestSuite = serde_yaml::from_str(yaml)?;
        Ok(Self { schema })
    }

    /// 创建新的生成器
    pub fn new(schema: TestSuite) -> Self {
        Self { schema }
    }

    /// 生成 Rust 测试代码
    pub fn generate(&self) -> String {
        let mut code = String::new();

        // 文件头注释
        code.push_str("// Generated by tests/generator/\n");
        code.push_str("// DO NOT EDIT MANUALLY\n");
        code.push_str(&format!("// From: {}\n", self.schema.name));
        code.push_str(&format!("// Generated at: {}\n\n", chrono::Local::now().format("%Y-%m-%d %H:%M:%S")));

        // 引入必要的依赖
        code.push_str("use crate::common::*;\n\n");

        // 生成每个测试
        for test_case in &self.schema.tests {
            let test_code = templates::generate_test(test_case);
            code.push_str(&test_code.to_string());
            code.push('\n');
        }

        code
    }

    /// 写入生成的代码到文件
    pub fn write_to(&self, path: &Path) -> Result<()> {
        let code = self.generate();
        std::fs::write(path, code)?;
        Ok(())
    }

    /// 批量生成所有测试套件
    pub fn generate_all() -> Result<()> {
        let suite_dir = Path::new("tests/suite");
        let generated_dir = Path::new("tests/generated");

        // 确保 generated 目录存在
        std::fs::create_dir_all(generated_dir)?;

        // 遍历所有 YAML 文件
        for entry in std::fs::read_dir(suite_dir)? {
            let entry = entry?;
            let path = entry.path();

            // 只处理 .yaml 文件
            if path.extension().and_then(|s| s.to_str()) != Some("yaml") {
                continue;
            }

            // 生成测试代码
            let generator = Self::from_yaml(&path)?;
            let stem = path.file_stem()
                .and_then(|s| s.to_str())
                .ok_or_else(|| anyhow::anyhow!("Invalid file name"))?;

            let output_path = generated_dir.join(format!("{}.rs", stem));
            generator.write_to(&output_path)?;

            println!("✅ Generated: {}", output_path.display());
        }

        Ok(())
    }
}

// 导出到测试模块
pub use templates::{generate_test, TestName};

/// 测试名称辅助 trait
pub trait TestName {
    fn to_snake_case(&self) -> String;
    fn to_test_name(&self) -> String;
}

impl TestName for String {
    fn to_snake_case(&self) -> String {
        self.chars()
            .map(|c| {
                if c.is_whitespace() {
                    '_'
                } else if c.is_ascii_alphanumeric() {
                    c.to_ascii_lowercase()
                } else {
                    '_'
                }
            })
            .collect::<String>()
            .split('_')
            .filter(|s| !s.is_empty())
            .collect::<Vec<_>>()
            .join("_")
    }

    fn to_test_name(&self) -> String {
        format!("test_{}", self.to_snake_case())
    }
}
