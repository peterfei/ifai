// generate_tests.rs
//
// 测试代码生成器
// 使用方法: cargo run --bin generate_tests

use std::fs;
use std::path::Path;

fn main() {
    println!("生成测试代码...");

    if let Err(e) = generate_tests() {
        eprintln!("测试生成失败: {}", e);
        std::process::exit(1);
    }

    println!("测试代码生成完成！");
}

fn generate_tests() -> Result<(), Box<dyn std::error::Error>> {
    // 获取当前二进制文件所在目录，然后向上找到 src-tauri
    let exe_path = std::env::current_exe()?;
    let mut base_path = exe_path.as_path();

    // 向上遍历找到 src-tauri 目录
    loop {
        base_path = base_path.parent().unwrap();
        if base_path.ends_with("src-tauri") {
            break;
        }
        // 防止无限循环
        if base_path.as_os_str().is_empty() {
            return Err("Cannot find src-tauri directory".into());
        }
    }

    let base_dir = base_path;
    let suite_dir = base_dir.join("src/bin/ifai/tests/suite");
    let generated_dir = base_dir.join("src/bin/ifai/tests/generated");

    println!("Base dir: {:?}", base_dir);
    println!("Suite dir: {:?}", suite_dir);
    println!("Generated dir: {:?}", generated_dir);

    // 创建生成目录
    fs::create_dir_all(&generated_dir)?;

    // 处理每个 YAML 测试套件
    for entry in fs::read_dir(suite_dir)? {
        let entry = entry?;
        let path = entry.path();

        if path.extension().and_then(|s| s.to_str()) == Some("yaml") ||
           path.extension().and_then(|s| s.to_str()) == Some("yml") {
            println!("正在处理: {:?}", path);

            // 读取 YAML 内容
            let yaml_content = fs::read_to_string(&path)?;

            // 解析 YAML
            let schema: serde_yaml::Value = serde_yaml::from_str(&yaml_content)?;

            // 生成 Rust 测试代码
            let test_code = generate_test_from_schema(&schema, &path)?;

            // 写入生成的测试文件
            let file_name = path.file_stem()
                .and_then(|s| s.to_str())
                .ok_or("Invalid file name")?;
            let output_path = generated_dir.join(format!("{}.rs", file_name));
            fs::write(&output_path, test_code)?;

            println!("生成测试文件: {:?}", output_path);
        }
    }

    // 生成 mod.rs 以导出所有测试
    generate_mod_rs(&generated_dir)?;

    Ok(())
}

fn generate_test_from_schema(
    schema: &serde_yaml::Value,
    yaml_path: &Path,
) -> Result<String, Box<dyn std::error::Error>> {
    let suite = schema.get("test_suite")
        .ok_or("Missing test_suite")?;

    let name = suite.get("name")
        .and_then(|v| v.as_str())
        .unwrap_or("Unknown");

    let tests = suite.get("tests")
        .and_then(|v| v.as_sequence())
        .ok_or("Missing tests")?;

    let mut code = String::new();

    // 文件头
    code.push_str("// Generated by generate_tests.rs\n");
    code.push_str("// DO NOT EDIT MANUALLY\n");
    code.push_str(&format!("// Source: {}\n", yaml_path.display()));
    code.push_str(&format!("// Suite: {}\n\n", name));

    // 导入
    code.push_str("use crate::tests::common::*;\n\n");

    // 生成每个测试
    for test in tests {
        if let Some(test_code) = generate_single_test(test) {
            code.push_str(&test_code);
            code.push_str("\n");
        }
    }

    Ok(code)
}

fn generate_single_test(test: &serde_yaml::Value) -> Option<String> {
    let name = test.get("name")?.as_str()?;
    let description = test.get("description").and_then(|v| v.as_str());
    // 使用拼音或数字ID来避免中文字符
    let test_name = to_test_name(name);

    let mut code = String::new();

    code.push_str("#[tokio::test]\n");
    code.push_str("#[serial_test::serial]\n");
    code.push_str(&format!("async fn test_{}() {{\n", test_name));

    if let Some(desc) = description {
        code.push_str(&format!("    // {}\n", desc));
    }

    // 检查是否需要 Mock
    let needs_mock = test.get("when")
        .and_then(|w| w.get("mock_response"))
        .is_some()
        || test.get("when")
        .and_then(|w| w.get("mock_streaming"))
        .is_some();

    if let Some(given) = test.get("given") {
        code.push_str(&generate_given(given, needs_mock));
    }

    // 从 given 中获取 args
    let args = test.get("given")
        .and_then(|g| g.get("args"))
        .and_then(|a| a.as_sequence());

    if let Some(when) = test.get("when") {
        code.push_str(&generate_when(when, args, needs_mock));
    }

    if let Some(then) = test.get("then") {
        code.push_str(&generate_then(then));
    }

    code.push_str("}\n");
    Some(code)
}

fn generate_given(given: &serde_yaml::Value, needs_mock: bool) -> String {
    let mut code = String::new();

    if needs_mock {
        code.push_str("    let mut env = TestEnv::with_mock().await.unwrap();\n");
    } else {
        code.push_str("    let mut env = TestEnv::new().await.unwrap();\n");
    }

    if let Some(env_vars) = given.get("env") {
        if let Some(mapping) = env_vars.as_mapping() {
            for (key, value) in mapping {
                if let (Some(k), Some(v)) = (key.as_str(), value.as_str()) {
                    code.push_str(&format!("    env.set_env(\"{}\", \"{}\");\n", k, v));
                }
            }
        }
    }

    if let Some(config) = given.get("config") {
        if let Some(config_str) = config.as_str() {
            code.push_str(&format!("    env.write_config(\"{}\").await.unwrap();\n",
                config_str.escape_default()));
        }
    }

    // 支持 config_content（多行配置）
    if let Some(config_content) = given.get("config_content") {
        if let Some(config_str) = config_content.as_str() {
            code.push_str(&format!("    env.write_config(\"{}\").await.unwrap();\n",
                config_str.escape_default()));
        }
    }

    // 支持 stdin 输入
    if let Some(stdin) = given.get("stdin") {
        if let Some(stdin_str) = stdin.as_str() {
            code.push_str(&format!("    env.set_stdin(\"{}\");\n",
                stdin_str.escape_default()));
        }
    }

    // 支持 stdin_lines 输入（多行，用于 REPL 测试）
    if let Some(stdin_lines) = given.get("stdin_lines") {
        if let Some(lines) = stdin_lines.as_sequence() {
            let lines_str: Vec<String> = lines.iter()
                .filter_map(|v| v.as_str())
                .map(|s| s.to_string())
                .collect();
            let joined = lines_str.join("\\n");
            code.push_str(&format!("    env.set_stdin(\"{}\");\n", joined));
        }
    }

    code
}

fn generate_when(when: &serde_yaml::Value, given_args: Option<&serde_yaml::Sequence>, needs_mock: bool) -> String {
    let mut code = String::new();

    // Mock 设置
    if needs_mock {
        if let Some(response_file) = when.get("mock_response").and_then(|v| v.as_str()) {
            code.push_str(&format!("    // Mock response: {}\n", response_file));
            // 🔥 使用流式响应（CLI 使用 stream() 方法）
            code.push_str("    if let Some(mock) = env.mock_server() {\n");
            code.push_str("        mock.setup_streaming_response(vec![\"Hello from mock!\"]).await.unwrap();\n");
            code.push_str("    }\n");
        } else if when.get("mock_streaming").is_some() {
            code.push_str("    // Mock streaming response\n");
            code.push_str("    if let Some(mock) = env.mock_server() {\n");
            code.push_str("        mock.setup_streaming_response(vec![\"Hello\", \" World\"]).await.unwrap();\n");
            code.push_str("    }\n");
        }
    }

    // 优先使用 given 中的 args，其次使用 when 中的 args，最后使用默认值
    let args = given_args
        .or(when.get("args").and_then(|v| v.as_sequence()))
        .map(|v| v.iter()
             .filter_map(|a| a.as_str())
             .map(|a| format!("\"{}\"", a.escape_default()))
             .collect::<Vec<_>>())
        .unwrap_or_else(|| vec!["\"hello\"".to_string()]);

    code.push_str(&format!("    let output = env.run_cli(&[{}]).await.unwrap();\n",
        args.join(", ")));

    code
}

fn generate_then(then: &serde_yaml::Value) -> String {
    let mut code = String::new();

    // 处理 assert_success
    if let Some(success) = then.get("assert_success").and_then(|v| v.as_bool()) {
        if success {
            code.push_str("    output.assert_success();\n");
        } else {
            // 期望失败：检查退出状态不是成功
            code.push_str("    assert!(!output.status.success(), \"Command should fail but it succeeded\");\n");
        }
    }

    if let Some(text) = then.get("assert_contains").and_then(|v| v.as_str()) {
        code.push_str(&format!("    output.assert_contains(\"{}\");\n",
            text.escape_default()));
    }

    if let Some(pattern) = then.get("assert_match").and_then(|v| v.as_str()) {
        code.push_str(&format!("    output.assert_match(r\"{}\");\n",
            pattern.escape_default()));
    }

    if let Some(tool) = then.get("assert_tool_called").and_then(|v| v.as_str()) {
        code.push_str(&format!("    output.assert_tool_called(\"{}\");\n",
            tool.escape_default()));
    }

    if let Some(count) = then.get("assert_token_count").and_then(|v| v.as_u64()) {
        code.push_str(&format!("    output.assert_token_count({});\n", count));
    }

    if then.get("assert_compression_triggered").and_then(|v| v.as_bool()).unwrap_or(false) {
        code.push_str("    output.assert_compression_triggered();\n");
    }

    if let Some(threshold) = then.get("assert_token_count_below").and_then(|v| v.as_u64()) {
        code.push_str(&format!("    output.assert_token_count_below({});\n", threshold));
    }

    if then.get("assert_system_prompt_preserved").and_then(|v| v.as_bool()).unwrap_or(false) {
        code.push_str("    output.assert_system_prompt_preserved();\n");
    }

    if let Some(count) = then.get("assert_recent_messages_count").and_then(|v| v.as_u64()) {
        code.push_str(&format!("    output.assert_recent_messages_count({});\n", count));
    }

    code
}

fn generate_mod_rs(generated_dir: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let mut mod_content = String::new();
    mod_content.push_str("// Generated by generate_tests.rs\n");
    mod_content.push_str("// DO NOT EDIT MANUALLY\n\n");

    for entry in fs::read_dir(generated_dir)? {
        let entry = entry?;
        let path = entry.path();

        if path.extension().and_then(|s| s.to_str()) == Some("rs") {
            if let Some(name) = path.file_stem().and_then(|s| s.to_str()) {
                if name != "mod" {
                    mod_content.push_str(&format!("pub mod {};\n", name));
                }
            }
        }
    }

    fs::write(generated_dir.join("mod.rs"), mod_content)?;
    Ok(())
}

fn to_snake_case(s: &str) -> String {
    s.chars()
        .map(|c| {
            if c.is_whitespace() || c == '-' || c == '/' {
                '_'
            } else if !c.is_alphanumeric() {
                '_'
            } else {
                c.to_ascii_lowercase()
            }
        })
        .collect::<String>()
        .split('_')
        .filter(|s| !s.is_empty())
        .collect::<Vec<&str>>()
        .join("_")
}

/// 将测试名称转换为有效的 Rust 标识符
fn to_test_name(name: &str) -> String {
    // 简单的拼音映射（仅处理常见中文）
    let pinyin_map = std::collections::HashMap::from([
        ("简单", "jian_dan"),
        ("提示词", "ti_shi_ci"),
        ("响应", "xiang_ying"),
        ("系统", "xi_tong"),
        ("生效", "sheng_xiao"),
        ("帮助", "bang_zhu"),
        ("信息", "xin_xi"),
        ("显示", "xian_shi"),
        ("版本", "ban_ben"),
        ("压缩", "ya_suo"),
        ("触发", "chu_fa"),
        ("保留", "bao_liu"),
        ("上下文", "shang_xia_wen"),
        ("工具", "gong_ju"),
        ("调用", "diao_yong"),
        ("长", "chang"),
        ("对话", "dui_hua"),
        ("自动", "zi_dong"),
        ("清理", "qing_li"),
        ("历史", "li_shi"),
    ]);

    let mut result = name.to_string();

    // 替换所有已知的中文字符
    for (chinese, pinyin) in &pinyin_map {
        result = result.replace(chinese, pinyin);
    }

    // 移除剩余的非 ASCII 字符
    let result: String = result.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else if c.is_whitespace() || c == '-' || c == '/' {
                '_'
            } else {
                '_' // 替换其他字符（包括未映射的中文）
            }
        })
        .collect();

    // 清理连续的下划线
    let result = result.split('_')
        .filter(|s| !s.is_empty())
        .collect::<Vec<&str>>()
        .join("_");

    // 如果结果为空或全是数字，添加前缀
    if result.is_empty() || result.chars().all(|c| c.is_numeric()) {
        let hash = name.chars().map(|c| c as u32).sum::<u32>();
        format!("test_{:x}", hash)
    } else {
        result
    }
}
